#!/usr/bin/env python3
"""Writes _data/assets.yml: the figure module of each interactive figure, and
a short hash of the content of each script and stylesheet.

    python3 _scripts/asset-data.py          # Write the file.
    python3 _scripts/asset-data.py --check  # Fail if the file is not up to date (CI).

_includes/head.html uses the file. A page loads only the figure modules of its
figures. The URL of an asset changes only when the asset changes. Thus
browsers keep the files that did not change in their cache. Run this script
after you change a file in assets/js or assets/css, or after you add a figure.
Then commit the result.
"""
import hashlib
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
assets = sorted(p for d in ("assets/js", "assets/css") for p in (root / d).glob("*.*") if p.suffix in (".js", ".css"))

lines = ["# Generated by _scripts/asset-data.py; do not edit by hand.", "hash:"]
for p in assets:
    digest = hashlib.sha256(p.read_bytes()).hexdigest()[:10]
    lines.append(f"  /{p.relative_to(root).as_posix()}: {digest}")
lines.append("viz:")
seen = {}
for p in sorted((root / "assets/js").glob("viz-*.js")):
    module = p.stem.removeprefix("viz-")
    if module == "core":
        continue
    for name in re.findall(r'register\("([a-z0-9-]+)"', p.read_text()):
        if name in seen:
            sys.exit(f"figure {name} is registered in viz-{seen[name]}.js and in {p.name}")
        seen[name] = module
for name in sorted(seen):
    lines.append(f"  {name}: {seen[name]}")
text = "\n".join(lines) + "\n"

target = root / "_data/assets.yml"
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != text:
        sys.exit("_data/assets.yml is out of date: run python3 _scripts/asset-data.py and commit it")
    print("_data/assets.yml is up to date")
else:
    target.write_text(text)
    print(f"wrote {target.relative_to(root)}: {len(assets)} assets, {len(seen)} figures")
